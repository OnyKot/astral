import {writeFile} from 'node:fs/promises';
import path from 'node:path';
import {fileURLToPath} from 'node:url';

const allowedChannels = new Set(['stable', 'canary']);
const rawChannel = process.env.BUILD_CHANNEL?.toLowerCase() ?? '';
const channel = allowedChannels.has(rawChannel) ? rawChannel : 'stable';

const scriptDir = path.dirname(fileURLToPath(import.meta.url));
const buildChannelPath = path.resolve(scriptDir, '..', 'src-electron', 'common', 'build-channel.ts');
const buildConfigPath = path.resolve(scriptDir, '..', 'src-electron', 'common', 'build-config.ts');

const DEFAULT_STABLE_APP_URL = 'https://astraof.com';
const DEFAULT_LEGACY_APP_URL = 'https://asrtal.ru';
const DEFAULT_UPDATE_ORIGINS = ['https://astraof.com', 'https://asrtal.ru'];

function splitList(value) {
	return (value ?? '')
		.split(',')
		.map((item) => item.trim())
		.filter(Boolean);
}

function unique(values) {
	return [...new Set(values)];
}

function normalizeUrl(value) {
	let candidate = value.trim();
	if (!candidate.includes('://')) {
		candidate = `https://${candidate}`;
	}

	const parsed = new URL(candidate);
	parsed.hash = '';
	return parsed.toString().replace(/\/+$/, '');
}

function normalizeOrigin(value) {
	let candidate = value.trim();
	if (!candidate.includes('://')) {
		candidate = `https://${candidate}`;
	}

	return new URL(candidate).origin;
}

const stableAppUrl = normalizeUrl(process.env.ASTRAL_ELECTRON_STABLE_APP_URL ?? DEFAULT_STABLE_APP_URL);
const canaryAppUrl = normalizeUrl(process.env.ASTRAL_ELECTRON_CANARY_APP_URL ?? stableAppUrl);
const trustedAppUrls = unique([
	stableAppUrl,
	canaryAppUrl,
	DEFAULT_LEGACY_APP_URL,
	...splitList(process.env.ASTRAL_ELECTRON_TRUSTED_APP_URLS).map(normalizeUrl),
]);
const desktopUpdateOrigins = unique(
	(splitList(process.env.ASTRAL_ELECTRON_UPDATE_ORIGINS).length
		? splitList(process.env.ASTRAL_ELECTRON_UPDATE_ORIGINS)
		: DEFAULT_UPDATE_ORIGINS
	).map(normalizeOrigin),
);

const buildChannelContent = `/*
 * This file is generated by scripts/set-build-channel.mjs.
 * DO NOT EDIT MANUALLY.
 */

export type BuildChannel = 'stable' | 'canary';

const DEFAULT_BUILD_CHANNEL = '${channel}' as BuildChannel;

const envChannel = process.env.BUILD_CHANNEL?.toLowerCase();
export const BUILD_CHANNEL = (envChannel === 'canary' ? 'canary' : DEFAULT_BUILD_CHANNEL) as BuildChannel;
export const IS_CANARY = BUILD_CHANNEL === 'canary';
export const CHANNEL_DISPLAY_NAME = BUILD_CHANNEL;
`;

const buildConfigContent = `/*
 * This file is generated by scripts/set-build-channel.mjs.
 * DO NOT EDIT MANUALLY.
 */

export const BUILD_STABLE_APP_URL = ${JSON.stringify(stableAppUrl)} as const;
export const BUILD_CANARY_APP_URL = ${JSON.stringify(canaryAppUrl)} as const;
export const BUILD_TRUSTED_APP_URLS = ${JSON.stringify(trustedAppUrls)} as const;
export const BUILD_DESKTOP_UPDATE_ORIGINS = ${JSON.stringify(desktopUpdateOrigins)} as const;
`;

await writeFile(buildChannelPath, buildChannelContent, 'utf8');
await writeFile(buildConfigPath, buildConfigContent, 'utf8');
console.log(`Wrote ${buildChannelPath} with channel '${channel}'`);
console.log(`Wrote ${buildConfigPath} with ${trustedAppUrls.length} trusted app URL(s)`);

