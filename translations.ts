export const decodeMojibakeRu = (input: string) => {
  let next = input;
  for (const [broken, fixed] of mojibakePairs) {
    next = next.split(broken).join(fixed);
  }
  return next;
};

const normalizeDeep = <T,>(value: T): T => {
  if (typeof value === 'string') return decodeMojibakeRu(value) as T;
  if (Array.isArray(value)) return value.map((item) => normalizeDeep(item)) as T;
  if (value && typeof value === 'object') {
    const result: Record<string, unknown> = {};
    for (const [key, nested] of Object.entries(value as Record<string, unknown>)) {
      result[key] = normalizeDeep(nested);
    }
    return result as T;
  }
  return value;
};

